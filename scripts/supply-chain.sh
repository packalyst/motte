#!/usr/bin/env bash
# Supply-chain hardening for the panel stack (roadmap point 12c). OPT-IN and reversible — the
# normal `./manage.sh update` / `rebuild` path is unchanged and does not call anything here. Enable
# a piece only when you want it:
#
#   ./manage.sh pin           Resolve the external images to immutable @sha256 digests and write
#                             docker-compose.pinned.yml + images.lock. To USE the pins, set in .env:
#                                 COMPOSE_FILE=docker-compose.yml:docker-compose.pinned.yml
#                             (docker compose then layers the override on every command). Re-run
#                             `pin` deliberately to move to newer images.
#   ./manage.sh verify        cosign-verify the images listed in cosign-policy.txt (one per line:
#                             "image|identity-regexp|oidc-issuer" for keyless, or "image|key:PATH").
#                             Inert when the file is absent or cosign is not installed.
#   ./manage.sh health        Probe the local /health endpoint; exit 0 only when healthy.
#   ./manage.sh safe-rebuild  Health-gated rebuild: rebuild, then poll /health; on failure restore
#                             the previously-pinned image digests and rebuild again (automatic,
#                             non-destructive), and print how to roll the CODE back with git.
#
# It never runs `git reset` on its own. Test on a non-production host before relying on it.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$SCRIPT_DIR"

LOCK_FILE="images.lock"
PINNED_FILE="docker-compose.pinned.yml"
POLICY_FILE="cosign-policy.txt"

# External, pullable images keyed by their compose SERVICE name. Build services (api, ui, dnsmasq,
# turbotunnels) are local and pinned by their source commit, not a registry digest.
SERVICES=(docker-socket-proxy traefik headscale adguard vpn-router)
declare -A IMAGE_OF=(
  [docker-socket-proxy]="tecnativa/docker-socket-proxy:latest"
  [traefik]="traefik:v3.6"
  [headscale]="headscale/headscale:0.25"
  [adguard]="adguard/adguardhome:latest"
  [vpn-router]="tailscale/tailscale:latest"
)

c_red=$'\e[31m'; c_grn=$'\e[32m'; c_yel=$'\e[33m'; c_cya=$'\e[36m'; c_rst=$'\e[0m'
info() { echo -e "${c_cya}$*${c_rst}"; }
ok()   { echo -e "${c_grn}$*${c_rst}"; }
warn() { echo -e "${c_yel}$*${c_rst}"; }
err()  { echo -e "${c_red}$*${c_rst}" >&2; }

need_docker() {
  command -v docker >/dev/null 2>&1 || { err "docker not found"; exit 1; }
}

api_port() {
  local p
  p=$(grep -m1 '^API_PORT=' .env 2>/dev/null | cut -d= -f2 | sed 's/[[:space:]].*//' | tr -d '[:space:]')
  echo "${p:-8081}"
}

# resolve_digest <image-ref> -> prints "repo@sha256:..." or returns non-zero.
resolve_digest() {
  local ref="$1"
  docker pull -q "$ref" >/dev/null 2>&1 || { err "  pull failed: $ref"; return 1; }
  # RepoDigests is the registry content-addressed ref; take the one matching this repo.
  local repo="${ref%%:*}"
  docker image inspect "$ref" --format '{{range .RepoDigests}}{{println .}}{{end}}' 2>/dev/null \
    | grep -m1 "^${repo}@sha256:" || return 1
}

cmd_pin() {
  need_docker
  info "Resolving external images to immutable digests…"
  : > "$LOCK_FILE.tmp"
  {
    echo "# Generated by scripts/supply-chain.sh — digest pins for the external stack images."
    echo "# Enable with  COMPOSE_FILE=docker-compose.yml:docker-compose.pinned.yml  in .env."
    echo "services:"
  } > "$PINNED_FILE.tmp"
  local svc ref digest failed=0
  for svc in "${SERVICES[@]}"; do
    ref="${IMAGE_OF[$svc]}"
    if digest=$(resolve_digest "$ref"); then
      echo "$svc $digest" >> "$LOCK_FILE.tmp"
      printf '  %s:\n    image: %s\n' "$svc" "$digest" >> "$PINNED_FILE.tmp"
      ok "  $svc -> $digest"
    else
      warn "  $svc: could not resolve $ref (skipped)"
      failed=1
    fi
  done
  if [ "$failed" = 1 ] && [ ! -s "$LOCK_FILE.tmp" ]; then
    rm -f "$LOCK_FILE.tmp" "$PINNED_FILE.tmp"
    err "No digests resolved — not writing files."
    exit 1
  fi
  mv "$LOCK_FILE.tmp" "$LOCK_FILE"
  mv "$PINNED_FILE.tmp" "$PINNED_FILE"
  ok "Wrote $LOCK_FILE and $PINNED_FILE."
  warn "To apply, set COMPOSE_FILE=docker-compose.yml:$PINNED_FILE in .env, then rebuild."
}

cmd_verify() {
  need_docker
  if [ ! -f "$POLICY_FILE" ]; then
    warn "No $POLICY_FILE — nothing to verify. Add lines: image|identity-regexp|issuer  (keyless)"
    warn "or  image|key:/path/to/cosign.pub  (key-based). Only cosign-signed images can be verified."
    return 0
  fi
  if ! command -v cosign >/dev/null 2>&1; then
    err "cosign not installed — cannot verify. See https://docs.sigstore.dev/cosign/"
    exit 1
  fi
  local line img rest rc=0
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    case "$line" in \#*) continue ;; esac
    img="${line%%|*}"; rest="${line#*|}"
    info "Verifying $img …"
    if [[ "$rest" == key:* ]]; then
      if cosign verify --key "${rest#key:}" "$img" >/dev/null 2>&1; then ok "  OK (key)"; else err "  FAILED"; rc=1; fi
    else
      local identity="${rest%%|*}" issuer="${rest#*|}"
      if cosign verify --certificate-identity-regexp "$identity" --certificate-oidc-issuer "$issuer" "$img" >/dev/null 2>&1; then
        ok "  OK (keyless)"
      else err "  FAILED"; rc=1; fi
    fi
  done < "$POLICY_FILE"
  [ "$rc" = 0 ] && ok "All listed images verified." || { err "One or more images failed verification."; exit 1; }
}

# cmd_health [timeout-seconds]: poll /health until 2xx or timeout.
cmd_health() {
  local timeout="${1:-90}" port url waited=0
  port=$(api_port); url="http://127.0.0.1:${port}/health"
  info "Waiting for $url to be healthy (up to ${timeout}s)…"
  while [ "$waited" -lt "$timeout" ]; do
    if curl -fsS --max-time 5 "$url" >/dev/null 2>&1; then ok "Healthy."; return 0; fi
    sleep 5; waited=$((waited + 5))
  done
  err "Not healthy after ${timeout}s."
  return 1
}

cmd_safe_rebuild() {
  need_docker
  local prev_commit; prev_commit=$(git rev-parse HEAD 2>/dev/null || echo "unknown")
  # Snapshot the current pins so a failed rebuild can be rolled back to known-good images.
  local had_lock=0
  if [ -f "$LOCK_FILE" ]; then cp -a "$LOCK_FILE" "$LOCK_FILE.bak"; cp -a "$PINNED_FILE" "$PINNED_FILE.bak" 2>/dev/null || true; had_lock=1; fi

  info "Rebuilding (health-gated)…"
  bash "$SCRIPT_DIR/manage.sh" rebuild || warn "rebuild returned non-zero — continuing to health check"

  if cmd_health 120; then
    ok "Update healthy."
    rm -f "$LOCK_FILE.bak" "$PINNED_FILE.bak"
    return 0
  fi

  err "Health check FAILED after rebuild."
  if [ "$had_lock" = 1 ]; then
    warn "Restoring previously-pinned image digests and rebuilding…"
    mv "$LOCK_FILE.bak" "$LOCK_FILE"
    mv "$PINNED_FILE.bak" "$PINNED_FILE" 2>/dev/null || true
    bash "$SCRIPT_DIR/manage.sh" rebuild || true
    cmd_health 120 || err "Still unhealthy after restoring image pins."
  fi
  echo ""
  err "The new CODE is still checked out. To roll it back to the pre-update commit, run:"
  echo "    git -C \"$SCRIPT_DIR\" reset --hard $prev_commit && ./manage.sh rebuild"
  echo "  (review 'git log' first; this script never resets your repo on its own.)"
  return 1
}

case "${1:-}" in
  pin)           cmd_pin ;;
  verify)        cmd_verify ;;
  health)        shift; cmd_health "$@" ;;
  safe-rebuild)  cmd_safe_rebuild ;;
  *)
    echo "Usage: $0 {pin|verify|health [timeout]|safe-rebuild}"
    echo "See the header of this file for what each does. All opt-in; the normal update is unchanged."
    exit 2 ;;
esac
